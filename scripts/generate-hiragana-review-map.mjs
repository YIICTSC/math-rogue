import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import KuroshiroPackage from 'kuroshiro';
import KuromojiAnalyzer from 'kuroshiro-analyzer-kuromoji';

const ROOT = process.cwd();
const arg=(name)=>{const i=process.argv.indexOf(name);return i<0?undefined:process.argv[i+1];};
const REPORT = path.resolve(ROOT, arg('--report') || 'docs/language-check-all-elements.md');
const OUTPUT = path.resolve(ROOT, arg('--out') || 'src/data/hiraganaReviewExact.ts');
const KANJI = /[㐀-鿿々〆ヵヶ]/;
const READING_OVERRIDES = new Map([
  ['拳圧', 'けんあつ'],
  ['CD0。隙のない連撃', 'CD0。すきのないれんげき'],
  ['前方すべてに届く音圧', 'ぜんぽうすべてにとどくおんあつ'],
  ['PTAの圧', 'PTAのあつ'],
  ['購買部の圧', 'こうばいぶのあつ'],
]);

// Parse the reviewed vocabulary without requiring Node's experimental TS loader.
const vocabularyAst = ts.createSourceFile('readings.ts', fs.readFileSync(path.join(ROOT, 'src/data/hiraganaContextWords.ts'), 'utf8'), ts.ScriptTarget.Latest, true);
const vocabulary = new Map();
const readVocabulary = (node) => {
  if (ts.isPropertyAssignment(node) && ts.isStringLiteral(node.name) && ts.isStringLiteral(node.initializer)) vocabulary.set(node.name.text, node.initializer.text);
  ts.forEachChild(node, readVocabulary);
};
readVocabulary(vocabularyAst);
for (const pair of [['手札','てふだ'],['山札','やまふだ'],['捨て札','すてふだ'],['呪炎','じゅえん']]) vocabulary.set(...pair);
const vocabularyPattern = new RegExp([...vocabulary.keys()].sort((a,b)=>b.length-a.length).map(word=>word.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('|'),'g');
const convertOriginal = async (source, kuroshiro) => {
  const replacements = [];
  const protectedText = source.replace(vocabularyPattern, (word, offset) => {
    if (/[㐀-鿿々]/.test(word.at(-1)) && /[㐀-鿿々]/.test(source[offset+word.length]||'')) return word;
    const placeholder = `READINGTOKEN${replacements.length}TOKEN`;
    replacements.push([placeholder, vocabulary.get(word)]);
    return placeholder;
  });
  let converted = await kuroshiro.convert(protectedText, {to:'hiragana',mode:'normal'});
  for (const [placeholder, reading] of replacements) converted = converted.replaceAll(placeholder,reading);
  return converted;
};

const normalizeHiragana = (value) => value
  .replaceAll('しゅさつ', 'てふだ')
  .replaceAll('すてさつ', 'すてふだ')
  .replaceAll('やまさつ', 'やまふだ')
  .replace(/おはら(?=[がをのにへも、。…\s])/g, 'おなか')
  .replaceAll('たいしゅつかーど', 'かしだしカード')
  .replaceAll('いんくかめ', 'インクびん')
  .replaceAll('あとかたづけけ', 'あとかたづけ')
  .replaceAll('いっって', 'いって')
  .replaceAll('おきんがたりない', 'おかねがたりない')
  .replaceAll('じゅほのお', 'じゅえん')
  .replaceAll('あるま、', 'あるあいだ、');

if (!fs.existsSync(REPORT)) {
  throw new Error('Run `pnpm run audit:language:report` before generating the review map.');
}

const report = fs.readFileSync(REPORT, 'utf8');
const sectionStart = report.indexOf('## 全画面・イベント・データ文字列');
const sectionEnd = report.indexOf('\n## ', sectionStart + 5);
if (sectionStart < 0) throw new Error('The language report has no complete source-string section.');

const unescapeMarkdownCell = (value) => value
  .replaceAll('<br>', '\n')
  .replaceAll('\\|', '|')
  .replaceAll('\\\\', '\\');

const reviewRows = report
  .slice(sectionStart, sectionEnd < 0 ? report.length : sectionEnd)
  .split('\n')
  .filter((line) => /^\|[^-]/.test(line) && !line.startsWith('|区分'))
  .map((line) => line.slice(1, -1).split(/(?<!\\)\|/).map((cell) => cell.trim()))
  .filter((cells) => cells.length === 8 && (cells[7] === 'OK' || cells[7].includes('要確認')))
  .map((cells) => ({
    source: unescapeMarkdownCell(cells[4]),
    partiallyConverted: unescapeMarkdownCell(cells[5]),
  }))
  // A template sample is not an actual runtime lookup key. Dynamic forms keep
  // using the existing rules in textUtils instead of being hidden by this map.
  .filter(({ source }) => source && !source.includes('${'));

const Kuroshiro = KuroshiroPackage.default;
const kuroshiro = new Kuroshiro();
await kuroshiro.init(new KuromojiAnalyzer());

const entries = [];
const uniqueRows = new Map(reviewRows.map((entry) => [entry.source, entry]));
for (const { source } of [...uniqueRows.values()].sort((a, b) => a.source.localeCompare(b.source, 'ja'))) {
  const converted = normalizeHiragana(READING_OVERRIDES.get(source) || await convertOriginal(source, kuroshiro));
  if (converted !== source && !KANJI.test(converted)) entries.push([source, converted]);
}

const body = entries
  .map(([source, converted]) => `  ${JSON.stringify(source)}: ${JSON.stringify(converted)},`)
  .join('\n');
const output = `// Generated by scripts/generate-hiragana-review-map.mjs.\n`
  + `// Generated from original sentences, never from character-wise partial conversions.\n`
  + `export const HIRAGANA_REVIEW_EXACT: Readonly<Record<string, string>> = Object.freeze({\n${body}\n});\n`;

fs.writeFileSync(OUTPUT, output);
console.log(`Generated ${entries.length} reviewed hiragana readings at ${path.relative(ROOT, OUTPUT)}.`);
