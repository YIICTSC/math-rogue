import fs from 'node:fs';
import path from 'node:path';
import KuroshiroPackage from 'kuroshiro';
import KuromojiAnalyzer from 'kuroshiro-analyzer-kuromoji';

const ROOT = process.cwd();
const REPORT = path.join(ROOT, 'docs/language-check-all-elements.md');
const OUTPUT = path.join(ROOT, 'src/data/hiraganaReviewExact.ts');
const KANJI = /[㐀-鿿々〆ヵヶ]/;
const READING_OVERRIDES = new Map([
  ['拳圧', 'けんあつ'],
  ['CD0。隙のない連撃', 'CD0。すきのないれんげき'],
  ['前方すべてに届く音圧', 'ぜんぽうすべてにとどくおんあつ'],
  ['PTAの圧', 'PTAのあつ'],
  ['購買部の圧', 'こうばいぶのあつ'],
]);

if (!fs.existsSync(REPORT)) {
  throw new Error('Run `pnpm run audit:language:report` before generating the review map.');
}

const report = fs.readFileSync(REPORT, 'utf8');
const sectionStart = report.indexOf('## 全画面・イベント・データ文字列');
const sectionEnd = report.indexOf('\n## ', sectionStart + 5);
if (sectionStart < 0) throw new Error('The language report has no complete source-string section.');

const unescapeMarkdownCell = (value) => value
  .replaceAll('<br>', '\n')
  .replaceAll('\\|', '|')
  .replaceAll('\\\\', '\\');

const reviewRows = report
  .slice(sectionStart, sectionEnd < 0 ? report.length : sectionEnd)
  .split('\n')
  .filter((line) => /^\|[^-]/.test(line) && !line.startsWith('|区分'))
  .map((line) => line.slice(1, -1).split(/(?<!\\)\|/).map((cell) => cell.trim()))
  .filter((cells) => cells.length === 8 && (cells[7] === 'OK' || cells[7].includes('要確認')))
  .map((cells) => ({
    source: unescapeMarkdownCell(cells[4]),
    partiallyConverted: unescapeMarkdownCell(cells[5]),
  }))
  // A template sample is not an actual runtime lookup key. Dynamic forms keep
  // using the existing rules in textUtils instead of being hidden by this map.
  .filter(({ source }) => source && !source.includes('${'));

const Kuroshiro = KuroshiroPackage.default;
const kuroshiro = new Kuroshiro();
await kuroshiro.init(new KuromojiAnalyzer());

const entries = [];
const uniqueRows = new Map(reviewRows.map((entry) => [entry.source, entry]));
for (const { source, partiallyConverted } of [...uniqueRows.values()].sort((a, b) => a.source.localeCompare(b.source, 'ja'))) {
  const converted = READING_OVERRIDES.get(source) || await kuroshiro.convert(partiallyConverted, { to: 'hiragana', mode: 'normal' });
  if (converted !== source && !KANJI.test(converted)) entries.push([source, converted]);
}

const body = entries
  .map(([source, converted]) => `  ${JSON.stringify(source)}: ${JSON.stringify(converted)},`)
  .join('\n');
const output = `// Generated by scripts/generate-hiragana-review-map.mjs.\n`
  + `// Existing curated dictionaries take precedence over these readings.\n`
  + `export const HIRAGANA_REVIEW_EXACT: Readonly<Record<string, string>> = Object.freeze({\n${body}\n});\n`;

fs.writeFileSync(OUTPUT, output);
console.log(`Generated ${entries.length} reviewed hiragana readings at ${path.relative(ROOT, OUTPUT)}.`);
