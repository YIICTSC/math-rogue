import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';

// Keep generated source PNGs outside the repository. Only normalized WebP atlases
// and their provenance are shipped. Each input is one complete ImageGen 8x8 sheet.
const sources=JSON.parse(await fs.readFile(process.argv[2],'utf8'));
const cell=96,columns=['S','N','E','W','SE','SW','NE','NW'];
const rows=['walk-left','walk-right','attack','throw','swing','read','use','shoot'];
const sha=data=>crypto.createHash('sha256').update(data).digest('hex');
const median=values=>values.sort((a,b)=>a-b)[Math.floor(values.length/2)];
await fs.mkdir('assets/dungeons1',{recursive:true});
await fs.mkdir('public/sprites/dungeons1/actions',{recursive:true});
const original=JSON.parse(await fs.readFile('assets/dungeons1/hero-actions.json','utf8'));
const records=[{...original,key:'elementary-warrior',transformed:false}];

for(const source of sources){
 const reference=`public/sprites/wandering-student/${source.key}.webp`;
 const referenceBytes=await fs.readFile(reference),bytes=await fs.readFile(source.source);
 const raw=await sharp(bytes).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const {width,height}=raw.info;
 function cuts(axis,length,lo,hi){
  const result=[0];
  for(let i=1;i<8;i++){
   const expected=length*i/8,radius=length/8*.25;let best=Math.round(expected),score=Infinity;
   for(let p=Math.floor(expected-radius);p<=expected+radius;p++){
    let count=0;for(let k=lo;k<hi;k++){
     const x=axis==='x'?p:k,y=axis==='y'?p:k;
     if(raw.data[(y*width+x)*4+3]>180)count++;
    }
    const value=count*1000+Math.abs(p-expected);if(value<score){score=value;best=p;}
   }
   result.push(best);
  }
  result.push(length);return result;
 }
 const ys=cuts('y',height,0,width),frames=[];
 for(let row=0;row<8;row++){
  const xs=cuts('x',width,ys[row],ys[row+1]);
  for(let col=0;col<8;col++){
   const rect={left:xs[col],top:ys[row],width:xs[col+1]-xs[col],height:ys[row+1]-ys[row]};
   const frame=await sharp(bytes).extract(rect).ensureAlpha().raw().toBuffer({resolveWithObject:true});
   let visible=0;for(let i=3;i<frame.data.length;i+=4){frame.data[i]=frame.data[i]>180?255:0;if(frame.data[i])visible++;}
   if(visible<100)throw Error(`${source.key}: empty source cell ${row}/${col}`);
   const input=await sharp(frame.data,{raw:frame.info}).trim({threshold:12}).png().toBuffer();
   const meta=await sharp(input).metadata();frames.push({input,width:meta.width,height:meta.height});
  }
 }
 const ref=await sharp(referenceBytes).extract({left:0,top:0,width:128,height:128}).ensureAlpha().raw().toBuffer();
 let top=128,bottom=-1;
 for(let y=0;y<128;y++)for(let x=0;x<128;x++)if(ref[(y*128+x)*4+3]>160){top=Math.min(top,y);bottom=Math.max(bottom,y);}
 if(bottom<top)throw Error('Empty reference '+reference);
 const baseline=16+(bottom+1)/2;
 const scale=Math.min((bottom-top+1)/2/median(frames.slice(0,16).map(f=>f.height)),
  88/Math.max(...frames.map(f=>f.width)),(baseline-3)/Math.max(...frames.map(f=>f.height)));
 const layers=[];
 for(let i=0;i<64;i++){
  const f=frames[i],w=Math.max(1,Math.round(f.width*scale)),h=Math.max(1,Math.round(f.height*scale));
  layers.push({input:await sharp(f.input).resize(w,h,{kernel:'nearest'}).png().toBuffer(),left:i%8*cell+Math.floor((cell-w)/2),top:Math.floor(i/8)*cell+Math.round(baseline-h)});
 }
 const output=`public/sprites/dungeons1/actions/${source.key}.webp`;
 await sharp({create:{width:cell*8,height:cell*8,channels:4,background:'#00000000'}}).composite(layers).webp({lossless:true}).toFile(output);
 records.push({key:source.key,heroId:source.id,transformed:source.transformed,generator:'ImageGen',source:path.basename(source.source),sourceSha256:sha(bytes),sourceRetained:false,reference,referenceSha256:sha(referenceBytes),output,sha256:sha(await fs.readFile(output)),baseline,scale,frameCount:64});
 console.log('Normalized',source.key);
}
records.sort((a,b)=>a.key.localeCompare(b.key,'en'));
await fs.writeFile('assets/dungeons1/hero-actions-build.json',JSON.stringify({generator:'ImageGen',columns,rows,cell,frameCount:records.length*64,normalization:'One shared scale per atlas; bottom-center anchor matched to each shipped hero; nearest-neighbor; lossless WebP',assets:records},null,2)+'\n');
await fs.writeFile('src/data/dungeons1HeroActionKeys.ts','// Generated by scripts/dungeons1/build-hero-actions.mjs.\nexport const D1_HERO_ACTION_KEYS:ReadonlySet<string>=new Set('+JSON.stringify(records.map(r=>r.key),null,2)+');\n');
