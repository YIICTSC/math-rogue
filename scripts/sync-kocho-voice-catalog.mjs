import fs from 'node:fs';
const catalog=JSON.parse(fs.readFileSync('assets/kocho/voice-lines.json','utf8'));
const build=JSON.parse(fs.readFileSync('assets/kocho/voice-build.json','utf8'));
const partial=process.argv.includes('--allow-partial');
const durations={};
for(const hero of catalog.heroes){
 durations[hero.id]={};
 for(const [clip,text] of Object.entries(hero.lines)){
  const record=build.clips[`${hero.id}/${clip}`];
  if((!record||!fs.existsSync(`public/sfx/kocho-voices/${hero.id}/${clip}.ogg`))&&!partial)throw Error(`Missing voice ${hero.id}/${clip}`);
  durations[hero.id][clip]=Math.ceil((record?.seconds??Math.max(1.6,Math.min(5.5,text.length*.115+.6)))*1000);
 }
}
fs.writeFileSync('src/mini-games/kocho/voices.ts',`// Generated by scripts/sync-kocho-voice-catalog.mjs.\nimport type { KochoHeroId } from './guests';\n\nconst CARD_KEYS: Record<KochoHeroId, Record<string, string>> = ${JSON.stringify(catalog.cardKeys,null,2)};\n\nconst CLIP_MS: Record<KochoHeroId, Record<string, number>> = ${JSON.stringify(durations,null,2)};\n\nexport type KochoVoiceAction = ${catalog.actions.map(a=>JSON.stringify(a)).join(' | ')};\nexport const kochoSkillVoice = (hero: KochoHeroId, name: string) => CARD_KEYS[hero]?.[name];\nexport const kochoVoiceDuration = (hero: KochoHeroId, clip: string) => CLIP_MS[hero]?.[clip] ?? 0;\n`);
console.log(`Kocho voice catalog: ${Object.values(durations).reduce((n,v)=>n+Object.keys(v).length,0)} clips${partial?' (development draft)':''}`);
