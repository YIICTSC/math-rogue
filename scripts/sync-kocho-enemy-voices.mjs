import fs from 'node:fs';
const catalog=JSON.parse(fs.readFileSync('assets/kocho/enemy-voice-lines.json','utf8'));
const build=fs.existsSync('assets/kocho/enemy-voice-build.json')?JSON.parse(fs.readFileSync('assets/kocho/enemy-voice-build.json','utf8')):{clips:{}};
const partial=process.argv.includes('--allow-partial');
const entries={};
for(const enemy of catalog.heroes){
 const clips={};
 for(const key of Object.keys(enemy.lines)){
  const record=build.clips[`${enemy.id}/${key}`];
  if(!partial&&(!record||!fs.existsSync(`public/sfx/kocho-enemy-voices/${enemy.id}/${key}.ogg`)))throw Error(`Missing ${enemy.name}/${key}`);
  clips[key]=Math.ceil((record?.seconds??4)*1000);
 }
 entries[enemy.name]={id:enemy.id,clips};
}
fs.writeFileSync('src/mini-games/kocho/enemyVoices.ts',`// Generated by scripts/sync-kocho-enemy-voices.mjs.\nexport type KochoEnemyVoiceAction = 'spawn' | 'attack' | 'skill' | 'damage' | 'defeat';\nconst ENEMIES: Record<string, {id: string; clips: Partial<Record<KochoEnemyVoiceAction, number>>}> = ${JSON.stringify(entries,null,2)};\nexport const kochoEnemyVoice = (name: string, action: KochoEnemyVoiceAction) => {\n const enemy = ENEMIES[name];\n const duration = enemy?.clips[action];\n return enemy && duration ? {id: enemy.id, duration} : undefined;\n};\n`);
console.log(`Kocho enemies: ${Object.keys(entries).length}`);
