import fs from 'node:fs';
const moves=JSON.parse(fs.readFileSync('assets/kocho/super-moves.json','utf8'));
const partial=process.argv.includes('--allow-partial');
const build=fs.existsSync('assets/kocho/super-voice-build.json')?JSON.parse(fs.readFileSync('assets/kocho/super-voice-build.json','utf8')):{clips:{}};
const durations={original:{},rebel:{},akari:{}};
for(const m of moves){
 const rec=build.clips[`${m.hero}/${m.id}`];
 if(!partial&&(!rec||!fs.existsSync(`public/sfx/kocho-super-voices/${m.hero}/${m.id}.ogg`)))throw Error(`Missing ${m.hero}/${m.id}`);
 durations[m.hero][m.id]=Math.ceil((rec?.seconds??6)*1000);
}
fs.writeFileSync('src/mini-games/kocho/superData.ts',`// Generated by scripts/sync-kocho-supers.mjs.\nimport type { KochoSuperMove } from './superMoves';\nexport const SUPER_MOVES: KochoSuperMove[] = ${JSON.stringify(moves,null,2)};\nexport const SUPER_VOICE_MS: Record<string,Record<string,number>> = ${JSON.stringify(durations,null,2)};\n`);
console.log(`Kocho supers: ${moves.length} finishers`);
