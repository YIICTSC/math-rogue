/** Calibrate runtime action size against the shipped idle art; never resize individual poses. */
import fs from 'node:fs/promises';
import sharp from 'sharp';
import {createHash} from 'node:crypto';
const atlas=JSON.parse(await fs.readFile('assets/dungeons2/dedicated-animations-build.json','utf8'));
const hash=b=>createHash('sha256').update(b).digest('hex');
const median=values=>{const sorted=[...values].sort((a,b)=>a-b);return (sorted[1]+sorted[2])/2;};
function bounds(data,width,left,top,cell){
 let minY=cell,maxY=-1;
 for(let y=0;y<cell;y++)for(let x=0;x<cell;x++)if(data[((top+y)*width+left+x)*4+3]>64){minY=Math.min(minY,y);maxY=Math.max(maxY,y);}
 if(maxY<minY)throw new Error('Empty sprite');
 return {height:maxY-minY+1,bottom:maxY+1};
}
const metrics={},records=[];
for(const asset of atlas.assets){
 const idleBytes=await fs.readFile(asset.reference),actionBytes=await fs.readFile(asset.output);
 const idle=await sharp(idleBytes).ensureAlpha().raw().toBuffer(),action=await sharp(actionBytes).ensureAlpha().raw().toBuffer();
 const directions=[];
 for(let d=0;d<8;d++){
  const base=bounds(idle,512,d%4*128,Math.floor(d/4)*128,128);
  const walks=Array.from({length:4},(_,row)=>bounds(action,768,d*96,row*96,96).height);
  const height=median(walks);
  // One scale for every pose of this facing; preserve the walk's natural bob and attack reach.
  directions.push({scale:+(96*base.height/128/height).toFixed(8),foot:base.bottom/128,idleHeight:base.height,walkHeights:walks});
 }
 metrics[asset.key]=directions.map(({scale,foot})=>({scale,foot}));
 records.push({key:asset.key,idle:asset.reference,idleSha256:hash(idleBytes),actions:asset.output,actionSha256:hash(actionBytes),directions});
}
const module=`// Generated by scripts/dungeons2/generate-render-metrics.mjs. Do not edit.\nexport type D2HeroRenderMetric = {scale:number;foot:number};\nexport const D2_HERO_RENDER_METRICS: Record<string, readonly D2HeroRenderMetric[]> = ${JSON.stringify(metrics,null,2)};\n`;
await fs.writeFile('src/data/dungeons2HeroRenderMetrics.generated.ts',module);
await fs.writeFile('assets/dungeons2/render-metrics.json',JSON.stringify({version:1,alphaThreshold:64,method:'Median of four walking heights per direction, scaled to idle height. Feet share the idle baseline; all action rows retain this common scale.',records},null,2)+'\n');
const ratios=records.flatMap(r=>r.directions.flatMap(d=>d.walkHeights.map(h=>h*d.scale/96/(d.idleHeight/128))));
console.log(`Calibrated ${records.length} forms / ${ratios.length} walk frames; idle-relative heights ${Math.min(...ratios).toFixed(3)}–${Math.max(...ratios).toFixed(3)}.`);
