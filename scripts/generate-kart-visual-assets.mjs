import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const catalog = await readFile('src/three/protagonistCatalog.ts', 'utf8');
const start = catalog.indexOf('[', catalog.indexOf('export const PROTAGONISTS ='));
const end = catalog.indexOf('] as const;', start);
if (start < 0 || end < 0) throw new Error('Cannot read the GP protagonist catalog.');
const protagonists = JSON.parse(catalog.slice(start, end + 1));
const paths = [
  'sprites/online-titles/gp-logo.webp',
  'sprites/mini-game-titles/kart-landscape-v1.webp',
  'sprites/mini-game-titles/kart-portrait-v1.webp',
  'models/storybook/characters-v3.glb',
  'models/storybook/storybook-v1.glb',
  ...protagonists.map(p => {
    if (!/^(elementary|high-school|magic)-[a-z-]+$/.test(p.id)) throw new Error('Invalid protagonist ID.');
    return `models/protagonists/${p.id}.glb`;
  }),
];
const files = [];
for (const path of [...new Set(paths)]) {
  const bytes = await readFile(`public/${path}`);
  if (path.endsWith('.glb')) {
    if (bytes.toString('ascii', 0, 4) !== 'glTF') throw new Error(`Invalid model: ${path}`);
    const json = JSON.parse(bytes.subarray(20, 20 + bytes.readUInt32LE(12)).toString('utf8'));
    // Prepared models use Blob URLs. Every dependency must travel inside its GLB.
    if (['buffers', 'images'].some(key => json[key]?.some(v => v.uri && !v.uri.startsWith('data:')))) {
      throw new Error(`GP model has an external dependency: ${path}`);
    }
  }
  files.push({ path, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
}
const total = files.reduce((n, f) => n + f.bytes, 0);
const version = createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0, 16);
await writeFile('src/generated/kartVisualAssets.ts', `// Generated by scripts/generate-kart-visual-assets.mjs.\nexport const GP_VISUAL_VERSION = ${JSON.stringify(version)};\nexport const GP_VISUAL_BYTES = ${total};\nexport const GP_VISUAL_FILES = ${JSON.stringify(files, null, 2)} as const;\n`);
console.log(`GP visuals: ${files.length} files, ${(total / 1048576).toFixed(2)} MiB; no audio or other-game packs.`);
