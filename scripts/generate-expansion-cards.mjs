import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'docs/card-expansion-1000-additions.md');
const outputPath = path.join(root, 'src/data/expansionCards.ts');

const conditions = [
  ['LEFTMOST', '手札の左端から使用した時'],
  ['RIGHTMOST', '手札の右端から使用した時'],
  ['HAND_EVEN', '使用前の手札枚数が偶数の時'],
  ['HAND_ODD', '使用前の手札枚数が奇数の時'],
  ['ENERGY_ZERO_AFTER', '使用後のエナジーが0になる時'],
  ['ENERGY_EVEN_AFTER', '使用後のエナジーが偶数になる時'],
  ['NO_BLOCK', '使用時のブロックが0の時'],
  ['LOW_HP', 'HPが半分以下の時'],
  ['ENEMY_ATTACKING', '生存中の敵が攻撃予定の時'],
  ['ENEMY_NOT_ATTACKING', '生存中の敵が全員攻撃予定でない時'],
  ['DRAW_EVEN', '山札の枚数が偶数の時'],
  ['DISCARD_ODD', '捨て札の枚数が奇数の時'],
  ['NO_ATTACK_PLAYED', 'このターンにまだ攻撃していない時'],
  ['THIRD_OR_LATER', 'このターン3枚目以降に使用した時'],
  ['SAME_TYPE_IN_HAND', '手札に該当するカードがある時'],
  ['HIGHEST_COST_IN_HAND', '手札内で最高コストの時'],
];

const rewards = [
  ['DRAW', 'カードを1枚引く'],
  ['BLOCK', 'ブロック5を得る'],
  ['ENERGY', 'エナジー1を得る'],
  ['HEAL', 'HPを3回復する'],
  ['NEXT_DRAW', '次ターンのドロー+1'],
  ['NEXT_ENERGY', '次ターンのエナジー+1'],
  ['STRENGTH', 'ムキムキ1を得る'],
  ['DEXTERITY', 'カチカチ1を得る'],
  ['POISON_RANDOM', 'ランダムな敵にドクドク3を与える'],
  ['WEAK_ALL', '敵全体にへろへろ1を与える'],
  ['RECOVER_DISCARD', '捨て札から1枚を手札へ戻す'],
  ['UPGRADE_HAND', '手札の別カード1枚を強化する'],
  ['DISCOUNT_HAND', '手札の別カード1枚のコストを1下げる'],
  ['HAND_COUNT_BLOCK', '使用前の手札枚数と同じブロックを得る'],
];

const cardTypeLabels = {
  ATTACK: '攻撃',
  SKILL: 'スキル',
  POWER: 'パワー',
  SUMMON: 'サモン',
  STATUS: '状態',
  CURSE: '呪い',
};

const rows = fs.readFileSync(sourcePath, 'utf8').split(/\r?\n/).flatMap((line) => {
  if (!/^\|\d{3}\|/.test(line)) return [];
  const cells = line.slice(1, -1).split('|').map((cell) => cell.trim());
  return [{
    serial: Number(cells[0]),
    id: cells[1].replaceAll('`', ''),
    name: cells[2],
    type: cells[3],
    rarity: cells[4],
    cost: cells[5] === '-' ? 0 : cells[5] === 'X' ? 3 : Number(cells[5]),
  }];
});

if (rows.length !== 224) throw new Error(`Expected 224 expansion rows, got ${rows.length}`);
const invalidCostRows = rows.filter(row => !Number.isFinite(row.cost));
if (invalidCostRows.length > 0) throw new Error(`Expansion cards contain invalid costs: ${invalidCostRows.map(row => row.id).join(', ')}`);

const quote = (value) => JSON.stringify(value);
const generatedEffects = new Map();
const entries = rows.map((row, index) => {
  const [condition, conditionText] = conditions[Math.floor(index / rewards.length)];
  const [reward, rewardText] = rewards[index % rewards.length];
  const baseValue = 5 + (index % 7);
  const target = row.type === 'ATTACK' ? 'TargetType.ENEMY' : 'TargetType.SELF';
  const base = row.type === 'ATTACK'
    ? `damage: ${baseValue}, `
    : row.type === 'SKILL' || row.type === 'POWER'
      ? `block: ${baseValue}, `
      : '';
  const baseText = row.type === 'ATTACK'
    ? `${baseValue}ダメージ。`
    : row.type === 'SKILL' || row.type === 'POWER'
      ? `ブロック${baseValue}。`
      : '';
  const exhaust = row.type === 'STATUS' || row.type === 'CURSE' ? 'exhaust: true, ' : '';
  const visibleConditionText = condition === 'SAME_TYPE_IN_HAND'
    ? `手札に${cardTypeLabels[row.type] || '該当する'}カードがある時`
    : conditionText;
  const expansionDescription = `${visibleConditionText}、${rewardText}。`;
  // 番号ラベルは表示せず、固有共鳴の条件と追加効果だけを説明する。
  const description = `${baseText}${expansionDescription}`;
  generatedEffects.set(row.id, description);
  return `  ${row.id}: { name: ${quote(row.name)}, cost: ${row.cost}, type: CardType.${row.type}, target: ${target}, description: ${quote(description)}, ${base}${exhaust}rarity: ${quote(row.rarity)}, expansionEffect: { serial: ${row.serial}, condition: ${quote(condition)}, reward: ${quote(reward)} } },`;
});

const output = `// This file is generated by scripts/generate-expansion-cards.mjs.\nimport { Card, CardType, TargetType } from '../types';\n\nexport const EXPANSION_CARDS: Record<string, Omit<Card, 'id'>> = {\n${entries.join('\n')}\n};\n`;
fs.writeFileSync(outputPath, output);
const synchronizedMarkdown = fs.readFileSync(sourcePath, 'utf8').split(/\r?\n/).map((line) => {
  if (!/^\|\d{3}\|/.test(line)) return line;
  const cells = line.slice(1, -1).split('|').map((cell) => cell.trim());
  const id = cells[1].replaceAll('`', '');
  const effect = generatedEffects.get(id);
  if (!effect) return line;
  cells[6] = effect;
  cells[7] = `固有共鳴${cells[0]}`;
  return `|${cells.join('|')}|`;
}).join('\n');
fs.writeFileSync(sourcePath, synchronizedMarkdown);
console.log(`Wrote ${rows.length} cards to ${path.relative(root, outputPath)}`);
console.log(`Synchronized effects in ${path.relative(root, sourcePath)}`);
