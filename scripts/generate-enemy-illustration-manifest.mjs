import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const assetDirectory = path.join(root, 'public', 'enemy-illustrations');
const outputFile = path.join(root, 'src', 'data', 'enemyIllustrationManifest.ts');
const supportedExtension = /\.(?:webp|png|jpe?g|svg)$/i;

const files = fs.readdirSync(assetDirectory)
  .filter((file) => supportedExtension.test(file))
  .sort((left, right) => left.localeCompare(right, 'ja'));

const entries = new Map();
for (const file of files) {
  const baseName = file.replace(supportedExtension, '');
  for (const key of [
    baseName,
    baseName.normalize('NFC'),
    baseName.normalize('NFD'),
    baseName.normalize('NFKC'),
    baseName.normalize('NFKD'),
  ]) {
    if (!entries.has(key)) entries.set(key, file);
  }
}

const source = [
  '// Generated by scripts/generate-enemy-illustration-manifest.mjs.',
  '// Keys include Unicode-normalized aliases; values preserve the real disk name.',
  'export const ENEMY_ILLUSTRATION_MANIFEST: Readonly<Record<string, string>> = Object.freeze({',
  ...[...entries.entries()].map(([key, file]) => `  ${JSON.stringify(key)}: ${JSON.stringify(file)},`),
  '});',
  '',
].join('\n');

fs.writeFileSync(outputFile, source, 'utf8');
console.log(`Generated ${path.relative(root, outputFile)} (${files.length} files, ${entries.size} aliases).`);
