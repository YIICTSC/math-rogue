export const getMagicActStoryPart = (
  heroId: string,
  act: number,
  closestTargetName?: string,
  closestAffection = 0,
  storySet: StorySet = MAGIC_STORIES[0],
) => {
  if (isMagicMaleProtagonist(heroId)) {
    const protagonist = MAGIC_MALE_PROTAGONISTS.find((entry) => entry.id === heroId) ?? MAGIC_MALE_PROTAGONISTS[0];
    const actIndex = Math.max(0, Math.min(2, act - 1));
    const basePart = storySet.parts[actIndex] ?? MAGIC_STORIES[0].parts[actIndex];
    const relationshipText = closestTargetName && closestAffection > 0
      ? `${protagonist.name}は${closestTargetName}との約束を胸に、自分から未来を切り開くと決めた。好感度は${closestAffection}。`
      : `${protagonist.name}は${protagonist.specialty}の力を磨き、次に守るべき相手へ自分から手を伸ばすと決めた。`;
    return {
      title: `${basePart.title}・${protagonist.transformedTitle}の記録`,
      content: `${basePart.content.replace('魔法少女', '魔法騎士')}\n\n${relationshipText}`,
    };
  }
  const hero = MAGIC_HEROES.find((entry) => entry.id === heroId) ?? MAGIC_HEROES[0];
  const actIndex = Math.max(0, Math.min(2, act - 1));
  const basePart = storySet.parts[actIndex] ?? MAGIC_STORIES[0].parts[actIndex];
  const reflection = HERO_ACT_REFLECTIONS[hero.id]?.[actIndex] ?? hero.story;
  const relationshipText = closestTargetName && closestAffection > 0
    ? actIndex === 0
      ? `${closestTargetName}と交わした言葉は、慣れない二重生活を進む小さな支えになっている。`
      : actIndex === 1
        ? `${closestTargetName}との好感度は${closestAffection}。二人で過ごした時間が、迷いに負けない魔力へ変わっていく。`
        : `${closestTargetName}との約束を胸に、${hero.name}は自分の願いを封じさせないと決めた。`
    : 'まだ恋の答えは見つからない。それでも学園で得た友情が、次の一歩を支えている。';

  return {
    title: `${basePart.title}・${hero.attribute}の記録`,
    content: `${basePart.content}\n\n${reflection}\n\n${relationshipText}`,
  };
};
