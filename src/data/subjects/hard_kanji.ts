import { KanjiProblem } from '../kanjiData';

type Entry = [string, string, string?];

const buildOptions = (answer: string): string[] => {
    const variants = [
        `${answer}う`,
        answer.slice(0, -1),
        `${answer[0]}${answer}`,
        `${answer}ん`,
        `${answer}い`,
    ].filter((candidate) => candidate && candidate !== answer);
    return [answer, ...Array.from(new Set(variants)).slice(0, 3)];
};

const toProblems = (entries: Entry[], fallbackHint: string): KanjiProblem[] => entries.map(([question, answer, hint]) => ({
    question,
    answer,
    options: buildOptions(answer),
    hint: hint || fallbackHint,
}));

const annotateByAnswer = (entries: Entry[], hintByAnswer: Record<string, string>, fallbackHint: string): Entry[] =>
    entries.map(([question, answer, hint]) => [question, answer, hint || hintByAnswer[answer] || fallbackHint]);

const annotateByIndex = (entries: Entry[], ranges: Array<[number, number, string]>): Entry[] =>
    entries.map(([question, answer, hint], index) => {
        const rangeHint = ranges.find(([start, end]) => index >= start && index < end)?.[2];
        return [question, answer, hint || rangeHint];
    });

const uniqueProblems = (items: KanjiProblem[]): KanjiProblem[] => {
    const seen = new Set<string>();
    return items.filter((item) => {
        const key = `${item.question}::${item.answer}`;
        if (seen.has(key)) return false;
        seen.add(key);
        return true;
    });
};

const withContextualDistractors = (items: KanjiProblem[]): KanjiProblem[] => {
    const answers = Array.from(new Set(items.map((item) => item.answer)));
    return items.map((item, index) => ({
        ...item,
        distractorPool: [1, 2, 3]
            .map((offset) => answers[(index + offset) % answers.length])
            .filter((candidate) => candidate !== item.answer),
    }));
};

