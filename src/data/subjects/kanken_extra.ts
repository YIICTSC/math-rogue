import { KanjiProblem } from '../kanjiData';

type Entry = [question: string, answer: string, hint: string];

const buildOptions = (answer: string): [string, string, string, string] => {
    const variants = [
        answer.replace(/じ/g, 'ぢ'),
        answer.replace(/ず/g, 'づ'),
        answer.replace(/し/g, 'じ'),
        answer.replace(/つ/g, 'づ'),
        answer.slice(0, -1),
        `${answer}う`,
        `${answer[0]}${answer}`,
        `${answer}い`,
        `${answer}ん`,
    ].filter((candidate) => candidate && candidate !== answer);

    return [answer, ...Array.from(new Set(variants)).slice(0, 3)] as [string, string, string, string];
};

const problems = (entries: Entry[]): KanjiProblem[] => entries.map(([question, answer, hint]) => ({
    question,
    answer,
    options: buildOptions(answer),
    hint,
}));

