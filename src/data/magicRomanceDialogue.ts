const getFixedDialogue = (dialogues: Record<string, FixedRomanceDialogue[]>, id: string, stageIndex: number) =>
  (dialogues[id] ?? dialogues.AKARI ?? TARGET_DIALOGUES.REN)[stageIndex] ?? (dialogues[id] ?? dialogues.AKARI ?? TARGET_DIALOGUES.REN)[0];

const getDialogueLines = (dialogue: FixedRomanceDialogue, heroId: string, fallbackHeroId: string) =>
  dialogue.linesByHero[heroId] ?? dialogue.linesByHero[fallbackHeroId] ?? [];

const applyRewardChoices = (
  fixedChoices: [FixedRomanceChoice, FixedRomanceChoice, FixedRomanceChoice],
  rewardChoices: Array<Omit<MagicRomanceChoiceDefinition, 'response'>>,
): MagicRomanceChoiceDefinition[] =>
  rewardChoices.map((rewardChoice, index) => ({
    ...rewardChoice,
    label: fixedChoices[index]?.label ?? rewardChoice.label,
    response: (fixedChoices[index]?.response ?? '') + '\n' + RESPONSE_BY_REWARD[rewardChoice.rewardKind],
  }));

export const getMagicRomanceDialogue = (
  heroId: string,
  targetId: string,
  stageIndex: number,
): MagicRomanceDialogueDefinition => {
  const safeStage = Math.max(0, Math.min(4, stageIndex));

  if (isMagicMaleProtagonist(heroId)) {
    const heroine = MAGIC_HEROES.find((entry) => entry.id === targetId) ?? MAGIC_HEROES[0];
    const dialogue = getFixedDialogue(FEMALE_TARGET_DIALOGUES, heroine.id, safeStage);
    const lines = getDialogueLines(dialogue, heroId, 'REN');
    return {
      title: heroine.name + '・' + STAGE_TITLES[safeStage],
      description: dialogue.scene + '\n\n' + lines.join('\n'),
      choices: applyRewardChoices(dialogue.choices, MALE_REWARD_CHOICES[safeStage]),
    };
  }

  const target = ROMANCE_TARGETS.find((entry) => entry.id === targetId) ?? ROMANCE_TARGETS[0];
  const dialogue = getFixedDialogue(TARGET_DIALOGUES, target.id, safeStage);
  const lines = getDialogueLines(dialogue, heroId, 'AKARI');

  return {
    title: target.name + '・' + STAGE_TITLES[safeStage],
    description: dialogue.scene + '\n\n' + lines.join('\n'),
    choices: applyRewardChoices(dialogue.choices, REWARD_CHOICES[safeStage]),
  };
};

