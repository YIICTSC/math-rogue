export const getMagicVacationActStoryPart = (
  heroId: string,
  act: number,
  closestTargetName?: string,
  closestAffection = 0,
  storySet: StorySet = MAGIC_VACATION_STORIES[0],
) => {
  const actIndex = Math.max(0, Math.min(2, act - 1));
  const basePart = storySet.parts[actIndex] ?? MAGIC_VACATION_STORIES[0].parts[actIndex];

  if (isMagicMaleProtagonist(heroId)) {
    const protagonist = MAGIC_MALE_PROTAGONISTS.find((entry) => entry.id === heroId) ?? MAGIC_MALE_PROTAGONISTS[0];
    const relationshipText = closestTargetName && closestAffection > 0
      ? `${protagonist.name}は${closestTargetName}と海辺で交わした約束を胸に、自分から次の景色へ進むと決めた。好感度は${closestAffection}。`
      : `${protagonist.name}は${protagonist.specialty}の力を夏の海で磨き、次に守るべき相手へ自分から手を伸ばすと決めた。`;

    return {
      title: `${basePart.title}・${protagonist.transformedTitle}の夏記録`,
      content: `${basePart.content}\n\n${relationshipText}`,
    };
  }

  const hero = MAGIC_HEROES.find((entry) => entry.id === heroId) ?? MAGIC_HEROES[0];
  const reflection = VACATION_HERO_ACT_REFLECTIONS[hero.id]?.[actIndex]
    ?? `${hero.name}は${hero.attribute}の魔法と潮風を味方に、この夏を自分の意思で進むと決めた。`;
  const relationshipText = closestTargetName && closestAffection > 0
    ? actIndex === 0
      ? `${closestTargetName}と海辺で交わした言葉が、慣れない魔法の休暇を進む小さな支えになっている。`
      : actIndex === 1
        ? `${closestTargetName}との好感度は${closestAffection}。二人で過ごした夏の時間が、迷いに負けない魔力へ変わっていく。`
        : `${closestTargetName}との次の夏の約束を胸に、${hero.name}は自分の願いを波にさらわせないと決めた。`
    : 'まだ恋の答えは見つからない。それでも海辺で得た友情と夏の思い出が、次の一歩を支えている。';

  return {
    title: `${basePart.title}・${hero.attribute}の夏記録`,
    content: `${basePart.content}\n\n${reflection}\n\n${relationshipText}`,
  };
};
