const normalizePair = (heroId: string, targetId: string) =>
  isMagicMaleProtagonist(heroId)
    ? { heroineId: targetId, maleId: heroId }
    : { heroineId: heroId, maleId: targetId };

const getVacationStageLine = (characterId: string, stageIndex: number) =>
  VACATION_STAGE_LINES[characterId]?.[Math.max(0, Math.min(4, stageIndex))] ?? '';

export const getMagicVacationRomanceDialogue = (heroId: string, targetId: string, stageIndex: number): MagicRomanceDialogueDefinition => {
  const safeStage = Math.max(0, Math.min(4, stageIndex));
  const base = getMagicRomanceDialogue(heroId, targetId, safeStage);
  const pair = normalizePair(heroId, targetId);
  const scene = VACATION_TARGET_SCENES[pair.maleId]?.[safeStage] ?? '潮風の中、二人は夏休みの時間を並んで過ごした。';
  const heroLine = getVacationStageLine(heroId, safeStage);
  const targetLine = getVacationStageLine(targetId, safeStage);
  const spokenLines = [
    heroLine ? (VACATION_SPEAKER_NAMES[heroId] ?? heroId) + '「' + heroLine + '」' : '',
    targetLine ? (VACATION_SPEAKER_NAMES[targetId] ?? targetId) + '「' + targetLine + '」' : '',
  ].filter(Boolean);
  return {
    ...base,
    description: scene + '。\n\n' + spokenLines.join('\n'),
    choices: base.choices.map(choice => {
      const responseParts = choice.response.split('\n').filter(Boolean);
      const rewardLine = responseParts[responseParts.length - 1] ?? '';
      return {
        ...choice,
        response: '潮風の中で「' + choice.label + '」を選び、二人だけの夏の思い出がまた一つ増えた。' + (rewardLine ? '\n' + rewardLine : ''),
      };
    }),
  };
};

export const getMagicVacationRomanceImageKey = (heroId: string, targetId: string, stage: number) => {
  const pair = normalizePair(heroId, targetId);
  return 'magic-romance-vacation:' + pair.heroineId + ':' + pair.maleId + ':r' + Math.max(1, Math.min(5, stage));
};

