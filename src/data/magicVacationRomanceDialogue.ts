export const getMagicVacationRomanceEnding = (heroId: string, targetId: string, affection: number) => {
  const rank = getMagicRomanceEndingRank(affection);
  const pair = normalizePair(heroId, targetId);
  const heroLines = MAGIC_VACATION_ENDING_LINES[heroId]?.[rank] ?? MAGIC_VACATION_ENDING_LINES[pair.heroineId]?.[rank];
  const targetLines = MAGIC_VACATION_ENDING_LINES[targetId]?.[rank] ?? MAGIC_VACATION_ENDING_LINES[pair.maleId]?.[rank];
  const suffix = rank === 'BOND' ? '-bond' : rank === 'SPECIAL' ? '-special' : rank === 'TRUE_ROMANCE' ? '-true' : '';
  return {
    rank,
    description: VACATION_ENDING_DESCRIPTIONS[rank],
    lines: [heroLines?.[0], targetLines?.[0], heroLines?.[1], targetLines?.[1]].filter((line): line is string => !!line),
    imagePath: 'sprites/magic/events/romance/vacation/' + pair.heroineId + '/' + pair.maleId + '/r6' + suffix + '.webp',
  };
};
