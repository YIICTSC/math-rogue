function makeGame(row: Design, id: string, variant: number, boss = false, reading?: string): Original {
  const [ja, en, family, item, hazard] = row, settings = SETTINGS[family];
  const spec: ActionSpec = { ...settings, item: item ?? settings.item, hazard: hazard ?? settings.hazard, family, variant, boss,
    goal: boss ? family === 'rhythm' ? 6 : ['aim', 'catch', 'duel', 'collect', 'sweep'].includes(family) ? 4 : family === 'throw' || family === 'chase' ? 2 : 1 : settings.goal,
    seconds: boss ? 12 : settings.seconds };
  return { id, title: L(ja, en, reading), cue: settings.cue, genre: boss ? 'boss' : family === 'rhythm' ? 'rhythm' : 'motion',
    icon: settings.icon, seconds: spec.seconds, boss: boss || undefined, quick: true,
    action: spec, mechanic: makeActionMechanic(spec) };
}

export const ACTION_CHAPTERS: readonly Original[][] = CHAPTERS.map((games, chapter) => [
  ...games.slice(0, -1).map((row, index) => makeGame(row, `action-${index + 1}`, chapter * 3 + index)),
  ...EXPANSIONS[chapter].map(([ja, en, hira, family, item, hazard], index) =>
    makeGame([ja, en, family, item, hazard], `cross-${index + 1}`, 100 + chapter * 14 + index, false, hira)),
  makeGame(games[games.length - 1], 'action-10', chapter * 3 + 9, true),
]);
